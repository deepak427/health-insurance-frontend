/** Helper to verify if an artifact was generated by the agent vs uploaded by user */
export function isAgentGeneratedArtifact(filename: string): boolean {
  if (!filename) return false;
  const lower = filename.toLowerCase();
  return (
    lower.startsWith("booking_confirmation_") ||
    lower.startsWith("quotation_comparison_") ||
    lower.endsWith("_insurance_guide.pdf") ||
    lower.endsWith("_guide.pdf") ||
    lower.endsWith("_summary.pdf")
  );
}

/** Extract readable messages from ADK session events */
export function eventsToMessages(events: ADKEvent[]): ChatMessage[] {
  const msgs: ChatMessage[] = [];
  // Collect pending artifacts from tool-result events to attach to the NEXT agent message
  const pendingArtifacts: string[] = [];

  for (const ev of events) {
    const artifactDelta = ev.actions?.artifactDelta;
    if (artifactDelta && Object.keys(artifactDelta).length > 0) {
      const generated = Object.keys(artifactDelta).filter(isAgentGeneratedArtifact);
      if (generated.length > 0) pendingArtifacts.push(...generated);
    }

    const parts = ev.content?.parts;
    const text = parts?.find((p: Record<string, unknown>) => typeof p.text === "string")?.text as string | undefined;

    if (ev.content?.role === "user") {
      // Skip tool/function response events — they aren't real user messages
      const isFunctionResponse = parts?.some((p: Record<string, unknown>) => "functionResponse" in p);
      if (!isFunctionResponse) {
        // Check for inlineData in parts
        const inlinePart = parts?.find(
          (p: Record<string, unknown>) => "inlineData" in p || "inline_data" in p
        ) as Record<string, { mimeType?: string; mime_type?: string; data?: string }> | undefined;
        const inlineObj = inlinePart?.inlineData || inlinePart?.inline_data;

        // Extract attachment name from the 📎 marker if present in text
        const attachMatch = text ? text.match(/\n?📎 (.+)$/) : null;
        let userAttachment: { name: string; mimeType: string; data?: string } | undefined = undefined;

        if (attachMatch) {
          const name = attachMatch[1].trim();
          const ext = name.split(".").pop()?.toLowerCase() || "";
          let mimeType = inlineObj?.mimeType || inlineObj?.mime_type || "application/octet-stream";
          if (mimeType === "application/octet-stream") {
            if (["png", "jpg", "jpeg", "webp", "gif", "bmp"].includes(ext)) {
              mimeType = `image/${ext === "jpg" ? "jpeg" : ext}`;
            } else if (ext === "pdf") {
              mimeType = "application/pdf";
            }
          }
          userAttachment = { name, mimeType, data: inlineObj?.data };
        } else if (inlineObj) {
          const mimeType = inlineObj.mimeType || inlineObj.mime_type || "application/octet-stream";
          const isImage = mimeType.startsWith("image/");
          const name = isImage ? "image.png" : "document.pdf";
          userAttachment = { name, mimeType, data: inlineObj.data };
        }

        const msgText = text || (userAttachment ? `📎 ${userAttachment.name}` : "");
        if (msgText || userAttachment) {
          msgs.push({ role: "user", text: msgText, userAttachment });
        }
      }
    } else if (ev.content?.role === "model" && text) {
      // Flush any pending artifacts onto this agent message
      const artifacts = pendingArtifacts.length > 0 ? [...pendingArtifacts] : undefined;
      pendingArtifacts.length = 0; // clear

      const last = msgs[msgs.length - 1];
      if (last?.role === "agent") {
        // Deduplicate: don't append if this text is already contained in the agent message
        const isDuplicate = last.text.includes(text.trim()) && text.trim().length > 40;
        if (!isDuplicate) {
          last.text += text;
        }
        if (artifacts) last.artifacts = [...(last.artifacts ?? []), ...artifacts];
      } else {
        msgs.push({ role: "agent", text, artifacts });
      }
    }
  }

  // If there are still pending artifacts after all events (edge case),
  // attach to the last agent message
  if (pendingArtifacts.length > 0) {
    const lastAgent = [...msgs].reverse().find((m) => m.role === "agent");
    if (lastAgent) {
      lastAgent.artifacts = [...(lastAgent.artifacts ?? []), ...pendingArtifacts];
    }
  }

  return msgs;
}

/** Get first user message as a preview title */
export function sessionPreview(events: ADKEvent[]): string {
  for (const ev of events) {
    if (ev.content?.role === "user") {
      // Skip tool/function response events
      const isFunctionResponse = ev.content.parts?.some((p: Record<string, unknown>) => p.functionResponse);
      if (isFunctionResponse) continue;
      const text = ev.content.parts?.find((p) => p.text)?.text;
      if (text) {
        const clean = text.replace(/\n?📎 .+$/, "").trim();
        return (clean || "Conversation").slice(0, 60) + (clean.length > 60 ? "…" : "");
      }
    }
  }
  return "New conversation";
}
