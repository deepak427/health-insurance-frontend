export async function* streamMessage(
  userId: string,
  sessionId: string,
  text: string,
  inlineData?: { mimeType: string; data: string }
): AsyncGenerator<{ text?: string; artifacts?: string[] }> {
  const parts: object[] = [{ text }];
  if (inlineData) parts.push({ inlineData });

  const res = await fetch(`${BASE_URL}/run_sse`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      appName: APP_NAME,
      userId,
      sessionId,
      newMessage: { role: "user", parts },
      streaming: true,
    }),
  });

  if (!res.ok || !res.body) throw new Error("SSE request failed");

  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";

  // Track accumulated text to deduplicate repeated agent turns
  let accumulatedText = "";

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;

    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split("\n");
    buffer = lines.pop() ?? "";

    for (const line of lines) {
      if (!line.startsWith("data:")) continue;
      const raw = line.slice(5).trim();
      if (!raw || raw === "[DONE]") continue;
      try {
        const event = JSON.parse(raw);

        // Collect agent-generated artifacts from ANY event that carries artifactDelta
        const artifactDelta = event?.actions?.artifactDelta;
        const rawArtifacts = artifactDelta && Object.keys(artifactDelta).length > 0
          ? Object.keys(artifactDelta).filter(isAgentGeneratedArtifact)
          : [];
        const artifacts = rawArtifacts.length > 0 ? rawArtifacts : undefined;

        // Only pull text from model-role content parts
        const content = event?.content;
        const isModelContent = content?.role === "model";
        const textPart = isModelContent
          ? content.parts?.find((p: { text?: string }) => p.text)?.text
          : undefined;

        if (textPart) {
          // Deduplicate: if the agent emits the same text again in a second turn, skip it
          if (accumulatedText.includes(textPart.trim()) && textPart.trim().length > 40) {
            continue;
          }
          accumulatedText += textPart;
        }

        if (textPart || artifacts) yield { text: textPart, artifacts };
      } catch {
        // skip malformed chunks
      }
    }
  }
}

